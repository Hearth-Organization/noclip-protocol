"""The game's recorded lines (Voice Studio, on the Hearth server).

    python3 Tools/Voice/make_voice.py header              -> Gem/Source/Player/VoiceLines.h (what the game picks from)
    python3 Tools/Voice/make_voice.py requests CMD MAN WOMAN OUT_DIR
                                                            -> agent requests (voice_lines) for the three voices' ids

lines.json holds the scripts: "command" (Foundation Command, a woman, over the radio, when an agent dies) and
"agent" (the agent's own lines by group, each made twice: a man's voice and a woman's, to match the agent in play).
"""
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
LINES = json.loads((HERE / "lines.json").read_text())
SCENES = {"command": "Dying", "man": "Agent man", "woman": "Agent woman"}


def folder(scene):
    return re.sub(r"[^a-z0-9]+", "-", scene.lower())


def command_lines():
    return [(f"cmd{i + 1:02d}", text) for i, text in enumerate(LINES["command"])]


def agent_lines():
    return [(group, f"{group}{i + 1:02d}", text) for group, texts in LINES["agent"].items() for i, text in enumerate(texts)]


def c_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def header():
    out = ["// Generated by Tools/Voice/make_voice.py from Tools/Voice/lines.json: the recorded lines (Voice Studio).",
           "#pragma once", "", "namespace NoclipProtocol::VoiceLines", "{",
           "    struct Line { const char* m_id; const char* m_text; };", "",
           f'    inline constexpr const char* CommandFolder = "assets/sounds/voice/{folder(SCENES["command"])}";',
           f'    inline constexpr const char* ManFolder = "assets/sounds/voice/{folder(SCENES["man"])}";',
           f'    inline constexpr const char* WomanFolder = "assets/sounds/voice/{folder(SCENES["woman"])}";', ""]
    lines = command_lines()
    out.append(f"    inline constexpr Line Command[{len(lines)}] = {{")
    out += [f"        {{ {c_string(i)}, {c_string(t)} }}," for i, t in lines]
    out.append("    };")
    for group, texts in LINES["agent"].items():
        name = group.capitalize()
        out.append(f"    inline constexpr Line {name}[{len(texts)}] = {{")
        out += [f"        {{ {c_string(f'{group}{i + 1:02d}')}, {c_string(t)} }}," for i, t in enumerate(texts)]
        out.append("    };")
    out += ["} // namespace NoclipProtocol::VoiceLines", ""]
    path = ROOT / "Gem" / "Source" / "Player" / "VoiceLines.h"
    path.write_text("\n".join(out))
    print("wrote", path)


def requests(cmd_voice, man_voice, woman_voice, out_dir):
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    batches = [("Dying", [{"id": i, "who": "Foundation Command", "voice": cmd_voice, "text": t, "mood": "Over radio", "speed": 1.0,
                           "room": 0, "usedIn": "Dying: the beacon map"} for i, t in command_lines()])]
    for scene, voice, who in (("Agent man", man_voice, "Agent (man)"), ("Agent woman", woman_voice, "Agent (woman)")):
        batches.append((scene, [{"id": i, "who": who, "voice": voice, "text": t, "mood": "Urgent" if g in ("spotted", "hurt") else "Calm",
                                 "speed": 1.0, "room": 0, "usedIn": f"Agent lines: {g}"} for g, i, t in agent_lines()]))
    names = []
    for scene, lines in batches:
        # Small batches: each request makes up to 15 lines, so one slow line doesn't hold everything up.
        for n in range(0, len(lines), 15):
            names.append({"scene": scene, "lines": lines[n:n + 15]})
    for k, args in enumerate(names):
        (out_dir / f"voice-{k + 1:02d}.args.json").write_text(json.dumps(args))
    print(len(names), "requests in", out_dir)


if __name__ == "__main__":
    if sys.argv[1] == "header":
        header()
    else:
        requests(*sys.argv[2:6])
