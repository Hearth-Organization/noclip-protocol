        bool Unlocked(Unlock unlock) const
        {
            switch (unlock)
            {
            case Unlock::None: return true;
            case Unlock::PowerII: return ResearchDone(0);
            case Unlock::StorageII: return ResearchDone(1);
            case Unlock::WeaponsI: return m_weaponsI;
            default: return false;
            }
        }
        bool Locked(Kind kind) const { return !Unlocked(Info(kind).m_unlock); }
        bool ResearchDone(int project) const
        {
            const ItemInfo& info = Info(project == 0 ? Kind::StudyPowerII : Kind::StudyStorageII);
            return m_studied[project][0] >= info.m_docs && m_studied[project][1] >= info.m_samples;
        }
        int Count(Kind kind, bool poweredOnly = false) const
        {
            int n = 0;
            for (const Placed& p : m_placed)
            {
                n += p.m_kind == kind && (!poweredOnly || p.m_powered) ? 1 : 0;
            }
            return n;
        }
        int Stored() const { return m_scrap + m_wire + m_fuel + m_docs + m_samples; }
        int Carried() const { return m_pack[0] + m_pack[1] + m_pack[2] + m_pack[4] + m_pack[5]; }
        int GearCount(const char* name) const
        {
            for (const auto& g : m_gear)
            {
                if (g.first == name)
                {
                    return g.second;
                }
            }
            return 0;
        }
        void AddGear(const char* name, int n)
        {
            for (auto& g : m_gear)
            {
                if (g.first == name)
                {
                    g.second += n;
                    return;
                }
            }
            m_gear.push_back({ AZStd::string(name), n });
        }

